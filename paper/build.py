def pct(x):
    """Percent with one decimal, rounding halves up (68.35 -> 68.4), as in the notes."""
    return str(Decimal(str(round(100 * x, 6))).quantize(Decimal("0.1"), rounding=ROUND_HALF_UP))


def load_summaries() -> dict[str, dict]:
    out = {}
    for f in RES.glob("*/*/summary.json"):
        out[f"{f.parent.parent.name}:{f.parent.name}"] = json.loads(f.read_text(encoding="utf-8"))
    for f in RES.glob("public/*/*/summary.json"):
        out[f"public:{f.parent.name}"] = json.loads(f.read_text(encoding="utf-8"))
    return out


def fields(s: dict) -> dict[str, str]:
    r = {}
    if "win_rate" in s:
        n = s.get("games")

        def exact(x):
            # summaries store rates rounded to 4 decimals; a rate over n games is k/n, so snap back to it before
            # rounding to one decimal (106/109 = 97.248%, not 97.25% -> 97.3%)
            return round(x * n) / n if isinstance(n, int) and n > 0 else x

        r["win"] = pct(exact(s["win_rate"]))
        ci = s.get("win_rate_ci95")
        if ci:
            r["lo"], r["hi"] = pct(exact(ci[0])), pct(exact(ci[1]))
        for k, name, f in (("mean_guesses_wins", "gw", "{:.2f}"), ("mean_guesses_fail7", "g7", "{:.2f}")):
            if s.get(k) is not None:
                r[name] = f.format(s[k])
        for k, name in (("invalid_turn_rate", "inv"), ("clue_contradiction_rate", "contra"),
                        ("nonword_guess_rate", "nonword")):
            if s.get(k) is not None:
                r[name] = pct(s[k])
        r["n"] = str(s.get("games", ""))
    for part in ("all", "clean"):
        if isinstance(s.get(part), dict) and "win_rate" in s[part]:
            for k, v in fields(s[part]).items():
                r[f"{part}-{k}"] = v
    return r


def seed_stats(S, split, suffix, runs):
    vals = [S[f"{split}:{M}{r}-best{suffix}"]["win_rate"] for r in runs if f"{split}:{M}{r}-best{suffix}" in S]
    if not vals:
        return None
    sd = statistics.stdev(vals) if len(vals) > 1 else 0.0
    return {"mean": pct(statistics.mean(vals)), "sd": pct(sd), "k": str(len(vals))}


def write_numbers(S):
    lines = ["% Generated by paper/build.py from results/eval-v1. Do not edit.",
             "\\newcommand{\\R}[1]{\\ifcsname r@#1\\endcsname\\csname r@#1\\endcsname\\else\\textbf{pending}\\fi}"]
    for key, s in sorted(S.items()):
        for f, v in fields(s).items():
            lines.append(f"\\expandafter\\def\\csname r@{key}:{f}\\endcsname{{{v}}}")
    for rnd, seeds in (("v8", ["v8-s1", "v8-s2", "v8-s3"]), ("v10", ["v10-s1", "v10-s2"])):
        for split in ("select", "heldout"):
            for suffix, tag in (("", "alone"), ("-constrained-wordle-word", "word"), ("-retry3", "retry"),
                                ("-open", "open")):
                st = seed_stats(S, split, suffix, seeds)
                if st:
                    for f, v in st.items():
                        lines.append(f"\\expandafter\\def\\csname r@agg:{rnd}:{split}:{tag}:{f}\\endcsname{{{v}}}")
    (OUT / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return len(lines)


def invalid_by_turn():
    """Share of turns that are invalid, by turn number, among games still running (select, alone, strict)."""
    runs = {"v7 s1": "v7", "v8 s1": "v8", "v8 s3": "v9", "v10 s1": "v10"}
    rows = []
    for label, kernel in runs.items():
        name = label.replace(" ", "-")
        f = ROOT / "kaggle_runs" / kernel / "runs" / "eval" / "select" / f"{M}{name}-best" / "results.jsonl"
        if not f.exists():
            continue
        n, bad = [0] * 7, [0] * 7
        for line in f.read_text(encoding="utf-8").splitlines():
            for k, t in enumerate(json.loads(line)["turns"]):
                n[k + 1] += 1
                bad[k + 1] += not t["valid"]
        rows += [{"model": label, "turn": k, "turns": n[k], "invalid": bad[k]} for k in range(1, 7)]
    ANA.mkdir(parents=True, exist_ok=True)
    path = ANA / "invalid_by_turn_select.csv"
    if rows:
        with path.open("w", newline="", encoding="utf-8") as h:
            w = csv.DictWriter(h, fieldnames=["model", "turn", "turns", "invalid"])
            w.writeheader()
            w.writerows(rows)
    elif path.exists():
        rows = list(csv.DictReader(path.open(encoding="utf-8")))
    return rows


def style(ax):
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(INK2)
    ax.tick_params(colors=INK2, labelsize=8)
    ax.yaxis.grid(True, color=GRID, linewidth=0.6)
    ax.set_axisbelow(True)


