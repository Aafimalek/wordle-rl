"""Build the paper's numbers and figures from the audited result files. Nothing in the PDF is typed by hand.

    python paper/build.py          # writes paper/numbers.tex, paper/figures/*.pdf, results/analysis/*.csv
    tectonic paper/main.tex        # compiles paper/main.pdf

Every number macro is \\R{<split>:<folder>:<field>}; a missing result prints "pending" in the PDF.
"""
