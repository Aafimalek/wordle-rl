def game_macros() -> list[str]:
    """Macros from results/analysis/games.json (written by paper/analysis.py)."""
    path = ANA / "games.json"
    if not path.exists():
        return []
    G = json.loads(path.read_text(encoding="utf-8"))
    out = []

    def put(key, value):
        out.append(f"\\expandafter\\def\\csname r@{key}\\endcsname{{{value}}}")

    for run, d in G.get("loss_breakdown", {}).items():
        for k in ("games", "lost", "lost_with_invalid", "nonwords", "first_time", "repeats", "next_valid",
                  "next_same", "lost_on_one_repeated", "games_with_nonword"):
            if k in d:
                put(f"g:{run}:{k.replace('_', '')}", d[k])
        if d["nonwords"]:
            put(f"g:{run}:fit", pct(d["nonwords_fit_clues"] / d["nonwords"]))
            put(f"g:{run}:near", pct(d["nonwords_one_letter_off"] / d["nonwords"]))
        for k, v in d["by_invalid_turns"].items():
            put(f"g:{run}:inv{k}", f"{v['won']} of {v['games']}")
    for pair, d in G.get("paired", {}).items():
        put(f"p:{pair}:bonly", d["b_only"])
        put(f"p:{pair}:aonly", d["a_only"])
        p = d["p"]
        put(f"p:{pair}:p", "$<$0.001" if p < 0.001 else f"{p:.3f}" if p < 0.1 else f"{p:.2f}")
    return out


def tables(S):
    T = OUT / "tables"
    T.mkdir(exist_ok=True)

    # every recorded run on the development and earlier test splits
    order = ["select", "heldout", "wordlebench", "jeffers", "rare", "full"]
    rows = []
    for key in sorted(S, key=lambda k: (order.index(k.split(":")[0]) if k.split(":")[0] in order else 99, k)):
        split, name = key.split(":", 1)
        s = S[key]
        if split not in order or "win_rate" not in s:
            continue
        f = fields(s)
        ci = f"{f['lo']}--{f['hi']}" if "lo" in f else "--"
        label = name.removeprefix("hf-").replace("constrained-wordle-word", "word-level").replace(
            "constrained-wordle", "token-level")
        mark = "$^\\dagger$" if "-v4-" in name else ""
        rows.append(f"{split} & \\texttt{{{label}}}{mark} & {f.get('n', '')} & {f['win']} & {ci} & "
                    f"{f.get('gw', '--')} & {f.get('inv', '--')} & {f.get('contra', '--')} \\\\")
    (T / "all_runs.tex").write_text("\n".join(rows) + "\n\\bottomrule\n", encoding="utf-8", newline="\n")

    # Kaggle sessions with a recorded duration (results/analysis/sessions.json, from the fetched job summaries)
    what = {"gemma-v2": "SFT v2 for Gemma 3 270M and SmolLM2-135M/360M; GRPO v2",
            "gemma-v3-final": "evaluations of SFT v3 and GRPO v3",
            "gemma-v3c": "benchmark-clean SFT v3c and its evaluations",
            "v5-s1": "SFT v5 seed 1",
            "ablate-word": "word-level decoding for v3c and v5",
            "v5-final": "earlier test of v5 s1; GRPO v5 (duration from the quota ledger)",
            "v5-seeds": "SFT v5 seeds 2 and 3",
            "v5-distill-r1": "self-distillation round",
            "v6": "v6 (stronger teacher) and v6w (whole-word output)",
            "v7": "v7 (drill) and v7s (strict drill)",
            "v8": "v8 seeds 1 and 2 (deep drill)",
            "v9": "v8 seed 3 and v9",
            "v10": "v10 seeds 1 and 2 (recovery round)",
            "final": "final test"}
    sp = ANA / "sessions.json"
    sess = json.loads(sp.read_text(encoding="utf-8")) if sp.exists() else {}
    sess.setdefault("v5-final", {"minutes": 228.0, "approx": True})
    lines, total = [], 0.0
    for name in what:
        if name in sess:
            m = sess[name]["minutes"]
            total += m
            lines.append(f"\\texttt{{fl-{name}}} & {what[name]} & {'about ' if sess[name].get('approx') else ''}{m:.0f} \\\\")
        elif name == "final":
            lines.append(f"\\texttt{{fl-{name}}} & {what[name]} & \\textbf{{pending}} \\\\")
    lines += ["\\midrule", f"Total recorded & & {total:.0f} ({total / 60:.1f} h) \\\\", "\\bottomrule"]
    (T / "sessions.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    path = ANA / "games.json"
    ex = json.loads(path.read_text(encoding="utf-8")).get("examples", {}) if path.exists() else {}
    titles = {"win": "(a) A win", "spelling_loss": "(b) Stuck on a rejected word", "trap_loss": "(c) A trap, word-level decoding",
              "recovered": "(d) Recovery after a rejection, v10 s1"}
    cells = []
    for kind, title in titles.items():
        if kind not in ex:
            continue
        g = ex[kind]
        lines = [f"\\multicolumn{{2}}{{@{{}}l}}{{\\textbf{{{title}}}: answer \\textsc{{{g['answer']}}}}} \\\\[2pt]"]
        for k, t in enumerate(g["turns"], 1):
            if t["valid"]:
                tiles = "".join(f"\\t{'xyg'[c]}{{{ch.upper()}}}" for ch, c in zip(t["guess"], t["feedback"],
                                                                                 strict=True))
                note = "".join("XYG"[c] for c in t["feedback"])
            else:
                tiles = "".join(f"\\tn{{{ch.upper()}}}" for ch in t["guess"])
                note = "rejected"
            lines.append(f"{k} & {tiles}\\;{{\\scriptsize\\ttfamily {note}}} \\\\")
        cells.append("\\begin{tabular}[t]{@{}r@{\\;\\,}l@{}}\n" + "\n".join(lines) + "\n\\end{tabular}")
    pairs = ["\n\\hfill\n".join(cells[i:i + 2]) for i in range(0, len(cells), 2)]
    (T / "examples.tex").write_text("\n\\\\[8pt]\n".join(pairs) + "\n", encoding="utf-8", newline="\n")
    return len(rows)


