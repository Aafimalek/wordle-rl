def cell(S, key, gw=False):
    if key not in S:
        return "–"
    f = fields(S[key])
    out = f"{f['win']}% ({f['lo']}–{f['hi']})" if "lo" in f else f"{f['win']}%"
    return out + (f" · {f['gw']}" if gw and "gw" in f else "")


